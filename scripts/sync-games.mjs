import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const gamesDirectory = join(projectRoot, 'src', 'games');
const indexPath = join(gamesDirectory, 'index.ts');
const modules = (await readdir(gamesDirectory))
  .filter((file) => /^[A-Za-z][A-Za-z0-9_-]*\.game\.ts$/.test(file))
  .sort();

if (modules.length === 0) throw new Error('Add at least one src/games/*.game.ts module.');

const imports = modules.map((file, index) => `import game${index} from './${file.slice(0, -3)}';`).join('\n');
const entries = modules.map((_, index) => `game${index}`).join(', ');
const source = `// Generated by scripts/sync-games.mjs. Add or remove a *.game.ts file, then run npm run sync:games.\n` +
  `import type { GameDefinition } from '../types/game';\n` +
  `${imports}\n\n` +
  `export const builtInGames: GameDefinition[] = [${entries}].sort((left, right) =>\n` +
  `  (left.catalogOrder ?? Number.MAX_SAFE_INTEGER) - (right.catalogOrder ?? Number.MAX_SAFE_INTEGER) || left.id.localeCompare(right.id)\n` +
  `);\n`;

const current = await readFile(indexPath, 'utf8').catch(() => '');
if (current !== source) {
  await writeFile(indexPath, source);
  console.log(`Updated game catalog (${modules.length} games).`);
}
